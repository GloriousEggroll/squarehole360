#!/usr/bin/env python3
"""Regenerate the GetData inline-leaf inputs from the user's own executable.

The native query experiment runs an exact copy of the XDK GetData function
(and its __savegprlr_26/__restgprlr_26 helpers). Those are Microsoft code, so
they are not distributed: this script derives them locally from

  - the recompiler output in generated/default/ (rexglue codegen), and
  - the loaded XEX image (build/bin/gow3-xex-image-dump), for the exact
    instruction words checked at startup,

and writes them to generated/native-getdata/.

Usage: generate_getdata.py [--project DIR] [--image PREFIX]
"""
import argparse, glob, json, os, re, struct, subprocess, sys

GETDATA = 0x82AFA708
SAVE26, SAVE26_WORDS = 0x82CC98F0, 8
RESTORE26, RESTORE26_WORDS = 0x82CC9940, 9
GETDATA_WORDS = 216
HEADER = "// Generated by tools/porting/generate_getdata.py from the user's executable. Do not edit.\n"
# Our only change to the exact body: let a proven native result bypass the
# global submission-marker gate (just before the "bge cr6,0x82afa78c" comparison).
PUBLISHED_ANCHOR = "\t// bge cr6,0x82afa78c\n\tif (!ctx.cr6.lt) goto loc_82AFA78C;\n"
PUBLISHED_INSERT = ("\t// Native query result may precede the unrelated global submission marker.\n"
                    "\tif (ctx.cr6.lt && Gow3NativeQueryResultAvailable(ctx.r6.u32, ctx.r3.u32, ctx.r11.u32, "
                    "uint8_t(ctx.r30.u32), base)) goto loc_82AFA78C;\n")

def function_body(sources, name):
    """Text of DEFINE_REX_FUNC(name) {...} after its opening line, through the closing brace."""
    head = "DEFINE_REX_FUNC(%s) {\n" % name
    for path in sources:
        text = open(path).read()
        start = text.find(head)
        if start < 0: continue
        start += len(head)
        end = text.find("\n}\n", start)
        if end < 0: raise SystemExit("unterminated %s in %s" % (name, path))
        return text[start:end + 3]
    raise SystemExit("%s not found in generated sources (run rexglue codegen first)" % name)

def words(meta, image, address, count):
    offset = address - meta["base"]
    return struct.unpack(">%dI" % count, image[offset:offset + 4 * count])

def array(name, address, values, address_name):
    lines = ["inline constexpr uint32_t %s=0x%08X;" % (address_name, address),
             "inline constexpr std::array<uint32_t,%d> %s{{" % (len(values), name)]
    for i in range(0, len(values), 6):
        lines.append("    " + "".join("0x%08Xu," % v for v in values[i:i + 6]))
    lines.append("}};")
    return "\n".join(lines) + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    parser.add_argument("--image", help="existing gow3-xex-image-dump prefix (default: dump game/default.xex)")
    args = parser.parse_args()
    root = args.project
    out = os.path.join(root, "generated", "native-getdata")
    os.makedirs(out, exist_ok=True)
    sources = sorted(glob.glob(os.path.join(root, "generated", "default", "*.cpp")))
    if not sources: raise SystemExit("generated/default is empty: run rexglue codegen first")

    leaf = function_body(sources, "sub_%08X" % GETDATA)
    if PUBLISHED_ANCHOR not in leaf: raise SystemExit("GetData body no longer has the expected comparison")
    published = leaf.replace(PUBLISHED_ANCHOR, PUBLISHED_INSERT + PUBLISHED_ANCHOR, 1)
    save = function_body(sources, "__savegprlr_26")
    restore = function_body(sources, "__restgprlr_26")
    open(os.path.join(out, "getdata_leaf_body.inc"), "w").write(
        HEADER + "REX_FUNC(GOW3_GETDATA_LEAF_NAME) {\n" + leaf)
    open(os.path.join(out, "getdata_published_body.inc"), "w").write(
        HEADER + "REX_FUNC(GOW3_GETDATA_LEAF_NAME) {\n" + published)
    open(os.path.join(out, "getdata_register_helpers.inc"), "w").write(
        HEADER + "GOW3_GETDATA_HELPER_LINKAGE REX_FUNC(GOW3_GETDATA_SAVE_NAME) {\n" + save +
        "GOW3_GETDATA_HELPER_LINKAGE REX_FUNC(GOW3_GETDATA_RESTORE_NAME) {\n" + restore)

    prefix = args.image
    if not prefix:
        tool = os.path.join(root, "build", "bin", "gow3-xex-image-dump")
        if not os.access(tool, os.X_OK): raise SystemExit("build gow3-xex-image-dump first, or pass --image")
        prefix = os.path.join(out, "default-image")
        subprocess.run([tool, os.path.join(root, "game"), "default.xex", prefix], check=True,
                       stdout=subprocess.DEVNULL)
    meta = json.load(open(prefix + ".json"))
    image = open(prefix + ".bin", "rb").read()
    open(os.path.join(out, "getdata_xex_words.inc"), "w").write(
        HEADER + "// Exact PPC instruction spans checked against the loaded XEX at startup.\n" +
        array("kInlineGetDataInstructions", GETDATA, words(meta, image, GETDATA, GETDATA_WORDS), "kInlineGetDataAddress") +
        array("kInlineSave26Instructions", SAVE26, words(meta, image, SAVE26, SAVE26_WORDS), "kInlineSave26Address") +
        array("kInlineRestore26Instructions", RESTORE26, words(meta, image, RESTORE26, RESTORE26_WORDS), "kInlineRestore26Address"))
    if not args.image:
        for suffix in (".bin", ".json"): os.remove(prefix + suffix)
    print("wrote", out)

main()
