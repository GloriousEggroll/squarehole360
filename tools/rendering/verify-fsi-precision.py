#!/usr/bin/env python3
"""Compile and GPU-test native packed raster operations, including the live ABI.

Requires an ordered-fragment-interlock Vulkan device. The GLSL and DXC variants
run the same overlapping-fragment fixtures; production additionally validates
polygon offset, exported depth and occlusion-query rejection. This is numerical
raster validation, not a claim of whole-game image equivalence.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess


def main():
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "reports/rendering/native-renderer/fsi-precision")
    parser.add_argument("--binary", type=Path, default=root / "build-native-renderer" /
                        ("gow3-native-fsi-test.exe" if os.name == "nt" else "gow3-native-fsi-test"))
    parser.add_argument("--depth-shader", type=Path,
                        help="Also verify a depth-only.fsi.spv generated by NativeShaderCompiler")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    sdk = root / "vendor/xenos-recomp/thirdparty/dxc-bin"
    compiler = sdk / "bin/x64" / ("dxc.exe" if os.name == "nt" else "dxc-linux")
    environment = os.environ.copy()
    if os.name != "nt":
        environment["LD_LIBRARY_PATH"] = str(sdk / "lib/x64") + (
            ":" + environment["LD_LIBRARY_PATH"] if environment.get("LD_LIBRARY_PATH") else "")
    results = []
    for mode, shader in (("glsl", None), ("hlsl", "fsi_precision_test.hlsl"),
                         ("production", "fsi_precision_production_test.hlsl")):
        binary = args.output / (mode + ".spv")
        log = args.output / (mode + ".log")
        with log.open("w") as output:
            if shader:
                command = [str(compiler), "-T", "ps_6_0", "-E", "main", "-HV", "2021", "-spirv",
                           "-fvk-use-dx-layout", "-fspv-target-env=vulkan1.2",
                           "-fspv-extension=SPV_EXT_fragment_shader_interlock",
                           "-fspv-extension=SPV_KHR_physical_storage_buffer",
                           "-I", str(root / "src/renderer/native"), "-Fo", str(binary),
                           str(root / "tools/rendering/native" / shader)]
                subprocess.run(command, env=environment, stdout=output, stderr=output, check=True, timeout=60)
            command = [str(args.binary)] + ([str(binary)] if shader else [])
            if mode == "production":
                command.append("--production")
            subprocess.run(command, env=environment, stdout=output, stderr=output, check=True, timeout=120)
        summary = next(line for line in log.read_text().splitlines() if line.startswith("PASS:"))
        results.append({"variant": mode, "passed": True, "summary": summary, "log": log.name})
        print(mode + ": " + summary, flush=True)
    if args.depth_shader:
        log = args.output / "builtin-depth.log"
        with log.open("w") as output:
            subprocess.run([str(args.binary), str(args.depth_shader), "--builtin-depth"],
                           env=environment, stdout=output, stderr=output, check=True, timeout=120)
        summary = next(line for line in log.read_text().splitlines() if line.startswith("PASS:"))
        results.append({"variant": "builtin-depth", "passed": True, "summary": summary, "log": log.name})
        print("builtin-depth: " + summary, flush=True)
    (args.output / "validation.json").write_text(json.dumps({
        "scope": "Native packed per-fragment raster operations; whole-game equivalence remains separate",
        "results": results,
    }, indent=2) + "\n")


if __name__ == "__main__":
    main()
